def _database_connection_string() -> str:
    dsn = st.secrets.get("PRIMARY_DATABASE_SQL_DSN")
    if not dsn:
        raise RuntimeError(
            "Configure PRIMARY_DATABASE_SQL_DSN in .streamlit/secrets.toml"
        )
    return str(dsn)


@st.cache_resource
def initialize_database() -> None:
    asyncio.run(_initialize_database(_database_connection_string()))


async def _initialize_database(connection_string: str) -> None:
    async with AsyncPostgresSaver.from_conn_string(connection_string) as checkpointer:
        await checkpointer.setup()

    async with await AsyncConnection.connect(connection_string) as connection:
        await connection.execute(
            """
            CREATE TABLE IF NOT EXISTS ingestion_sources (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                provider TEXT NOT NULL,
                file_path TEXT NOT NULL,
                UNIQUE (provider, file_path)
            )
            """
        )
        await connection.execute(
            """
            CREATE TABLE IF NOT EXISTS ingestion_threads (
                id TEXT PRIMARY KEY,
                ingestion_source_id BIGINT NOT NULL
                    REFERENCES ingestion_sources(id),
                last_processed_record_id TEXT,
                status TEXT NOT NULL DEFAULT 'running',
                error TEXT,
                is_current BOOLEAN NOT NULL DEFAULT TRUE,
                started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE (ingestion_source_id, id)
            )
            """
        )
        await connection.execute(
            """
            CREATE UNIQUE INDEX IF NOT EXISTS ingestion_threads_one_current
            ON ingestion_threads (ingestion_source_id)
            WHERE is_current
            """
        )
        await connection.commit()


async def _get_thread_status(
    connection_string: str,
    provider: str,
    file_path: str,
) -> dict[str, Any] | None:
    async with await AsyncConnection.connect(connection_string) as connection:
        cursor = await connection.execute(
            """
            SELECT
                source.id,
                thread.id,
                thread.status,
                thread.error,
                thread.last_processed_record_id,
                thread.updated_at
            FROM ingestion_sources AS source
            LEFT JOIN ingestion_threads AS thread
                ON thread.ingestion_source_id = source.id
                AND thread.is_current
            WHERE source.provider = %s AND source.file_path = %s
            """,
            (provider, file_path),
        )
        row = await cursor.fetchone()
        await connection.commit()
    if row is None:
        return None
    return {
        "source_id": row[0],
        "thread_id": row[1],
        "status": row[2],
        "error": row[3],
        "last_processed_record_id": row[4],
        "updated_at": row[5],
    }


def _status(provider: str, file_path: str) -> dict[str, Any] | None:
    return asyncio.run(
        _get_thread_status(_database_connection_string(), provider, file_path)
    )


def _event_stage(data: dict[str, Any]) -> str:
    stages = (
        ("extracted_records", "Extracting resumes"),
        ("transform_cleaned_records", "Cleaning records"),
        ("transform_enriched_records", "Enriching records"),
        ("transform_chunked_records", "Creating knowledge chunks"),
    )
    for key, label in stages:
        if data.get(key) is not None:
            return label
    if data.get("error"):
        return "Workflow failed"
    return "Starting workflow"


async def _ingest(
    provider: str,
    file_path: str,
    progress: Any,
    event_log: Any,
) -> None:
    registry = DomainRegistry()
    service = registry.get("service.resume.langgraph")
    if not isinstance(service, LanggraphResumeService):
        raise RuntimeError("LanggraphResumeService is not registered in the DomainRegistry")

    events = service.ingest_resume_records_to_knowledge_base(
        provider=provider,
        file_path=file_path,
    )
    seen_stages: list[str] = []
    async for event in events:
        data = event.get("data", {})
        stage = _event_stage(data)
        if stage not in seen_stages:
            seen_stages.append(stage)
        progress.progress(
            min(len(seen_stages) / 5, 1.0),
            text=stage,
        )
        event_log.write(
            "\n".join(f"{index}. {value}" for index, value in enumerate(seen_stages, 1))
        )


def _store_uploaded_file(uploaded_file: Any) -> Path:
    file_bytes = uploaded_file.getvalue()
    file_hash = hashlib.sha256(file_bytes).hexdigest()
    UPLOAD_DIRECTORY.mkdir(parents=True, exist_ok=True)
    destination = UPLOAD_DIRECTORY / f"{file_hash}.csv"
    if not destination.exists():
        destination.write_bytes(file_bytes)
    return destination


st.set_page_config(page_title="Resume Ingestion", page_icon="📄", layout="wide")
st.title("Resume ingestion")
st.caption("Process resume records into the knowledge base with resumable threads.")

missing_secrets = [key for key in REQUIRED_SECRETS if key not in st.secrets]
if missing_secrets:
    st.error(
        f"Missing secrets: {', '.join(missing_secrets)}. "
        "Add them to .streamlit/secrets.toml."
    )
    st.stop()

try:
    initialize_database()
except Exception as error:
    st.error(f"Database initialization failed: {error}")
    st.stop()

provider = st.selectbox("Provider", ["file", "url"], index=0)
if provider == "file":
    uploaded_file = st.file_uploader("Upload resume CSV", type=["csv"])
    if uploaded_file is None:
        st.info("Upload a CSV file to begin.")
        st.stop()
    selected_file_path = _store_uploaded_file(uploaded_file)
    file_path = str(selected_file_path.resolve())
else:
    file_path = st.text_input(
        "CSV URL",
        placeholder="https://example.com/resumes.csv",
    ).strip()
    if not file_path:
        st.info("Enter a CSV URL to begin.")
        st.stop()

current_status = _status(provider, file_path)

if current_status:
    status_value = current_status["status"]
    status_label = {
        "running": "Running",
        "succeeded": "Succeeded",
        "failed": "Failed - retry available",
    }.get(status_value, status_value.title())
    columns = st.columns(4)
    columns[0].metric("Status", status_label)
    columns[1].metric("Source ID", current_status["source_id"])
    columns[2].metric("Last processed ID", current_status["last_processed_record_id"] or "-")
    columns[3].metric("Current thread", str(current_status["thread_id"])[:12] + "...")
    if current_status["error"]:
        st.warning(current_status["error"])
else:
    st.info("This source has not been ingested yet. A thread will be created on run.")

run_label = "Retry failed ingestion" if current_status and current_status["status"] == "failed" else "Run ingestion"
run_column = st.columns(1)[0]
run_clicked = run_column.button(run_label, type="primary", use_container_width=True)

if run_clicked:
    progress = st.progress(0.0, text="Starting workflow")
    event_log = st.empty()
    with st.status("Ingesting resumes...", expanded=True) as status:
        try:
            asyncio.run(_ingest(provider, file_path, progress, event_log))
            progress.progress(1.0, text="Ingestion complete")
            status.update(label="Ingestion complete", state="complete", expanded=False)
            st.rerun()
        except Exception as error:
            status.update(label="Ingestion failed", state="error", expanded=True)
            st.exception(error)
